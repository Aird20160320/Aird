function w(
  bookId: string,
  word: string,
  reading: string,
  senses: [string, string][],
  example: [string, string],
  tip: string,
  related: string[],
): Word {
  return {
    id: `${bookId}-${reading}`,
    bookId,
    word,
    reading,
    senses: senses.map(([pos, def]) => ({ pos, def })),
    examples: [{ jp: example[0], zh: example[1] }],
    tip,
    synonyms: related,
  };
}

